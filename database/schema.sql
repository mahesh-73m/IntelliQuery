-- IntelliQuery schema. Two schemas:
--   business : the sample company database the AI is allowed to query
--   app      : application state; never visible to the read-only role
CREATE SCHEMA IF NOT EXISTS business;
CREATE SCHEMA IF NOT EXISTS app;

-- ============================= business =============================
CREATE TABLE business.categories (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE business.products (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    category_id  INTEGER NOT NULL REFERENCES business.categories(id),
    price        NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    cost         NUMERIC(10,2) NOT NULL CHECK (cost >= 0),
    stock        INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE business.customers (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL UNIQUE,
    city        VARCHAR(80)  NOT NULL,
    country     VARCHAR(60)  NOT NULL,
    created_at  DATE NOT NULL
);

CREATE TABLE business.orders (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INTEGER NOT NULL REFERENCES business.customers(id),
    order_date    DATE NOT NULL,
    status        VARCHAR(20) NOT NULL
                  CHECK (status IN ('pending','shipped','completed','cancelled','refunded')),
    total_amount  NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE business.order_items (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    INTEGER NOT NULL REFERENCES business.orders(id) ON DELETE CASCADE,
    product_id  INTEGER NOT NULL REFERENCES business.products(id),
    quantity    INTEGER NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX idx_products_category      ON business.products(category_id);
CREATE INDEX idx_orders_customer        ON business.orders(customer_id);
CREATE INDEX idx_orders_date            ON business.orders(order_date);
CREATE INDEX idx_orders_status          ON business.orders(status);
CREATE INDEX idx_order_items_order      ON business.order_items(order_id);
CREATE INDEX idx_order_items_product    ON business.order_items(product_id);
CREATE INDEX idx_customers_country      ON business.customers(country);

-- ============================== app ==================================
CREATE TABLE app.users (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(160) NOT NULL UNIQUE,
    full_name      VARCHAR(120) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    preferences    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app.conversations (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    title       VARCHAR(200) NOT NULL DEFAULT 'New conversation',
    state       JSONB NOT NULL DEFAULT '{}'::jsonb,   -- clarification state machine
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app.messages (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  INTEGER NOT NULL REFERENCES app.conversations(id) ON DELETE CASCADE,
    role             VARCHAR(12) NOT NULL CHECK (role IN ('user','assistant')),
    content          TEXT NOT NULL,
    payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app.query_history (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    conversation_id     INTEGER REFERENCES app.conversations(id) ON DELETE SET NULL,
    question            TEXT NOT NULL,
    generated_sql       TEXT,
    status              VARCHAR(12) NOT NULL CHECK (status IN ('success','error')),
    execution_time_ms   NUMERIC(10,2),
    row_count           INTEGER,
    error_message       TEXT,
    was_clarified       BOOLEAN NOT NULL DEFAULT FALSE,
    attempts            INTEGER NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app.clarification_history (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    conversation_id   INTEGER NOT NULL REFERENCES app.conversations(id) ON DELETE CASCADE,
    original_question TEXT NOT NULL,
    term_id           VARCHAR(80) NOT NULL,
    question          TEXT NOT NULL,
    options           JSONB NOT NULL,
    selected_option   VARCHAR(80),
    resolved          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at       TIMESTAMPTZ
);

CREATE TABLE app.saved_queries (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    name        VARCHAR(160) NOT NULL,
    question    TEXT NOT NULL DEFAULT '',
    sql_text    TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE app.evaluation_metrics (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       VARCHAR(40) NOT NULL,
    system       VARCHAR(20) NOT NULL CHECK (system IN ('basic','intelligent')),
    category     VARCHAR(30) NOT NULL,           -- 'all' or a dataset category
    metric_name  VARCHAR(60) NOT NULL,
    value        DOUBLE PRECISION NOT NULL,
    details      JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_conv_user          ON app.conversations(user_id, updated_at DESC);
CREATE INDEX idx_msg_conv           ON app.messages(conversation_id, id);
CREATE INDEX idx_qh_user            ON app.query_history(user_id, created_at DESC);
CREATE INDEX idx_clar_user          ON app.clarification_history(user_id, created_at DESC);
CREATE INDEX idx_saved_user         ON app.saved_queries(user_id);
CREATE INDEX idx_eval_run           ON app.evaluation_metrics(run_id);

-- ============================== grants ===============================
GRANT USAGE ON SCHEMA business TO iq_readonly;
GRANT SELECT ON ALL TABLES IN SCHEMA business TO iq_readonly;

GRANT USAGE ON SCHEMA app TO iq_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO iq_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO iq_app;
